//! Huntsman V2 Analog (ANSI, full size) layout with Razer firmware key IDs.
//! IDs come from Synapse's key table (inputID -> fwID).

pub struct Key {
    pub label: &'static str,
    pub id: u8,
    /// width in key units (1.0 = normal key)
    pub w: f32,
    /// height in rows (numpad + and Enter are 2)
    pub h: f32,
}

const fn k(label: &'static str, id: u8, w: f32) -> Key {
    Key { label, id, w, h: 1.0 }
}
const fn tall(label: &'static str, id: u8) -> Key {
    Key { label, id, w: 1.0, h: 2.0 }
}

