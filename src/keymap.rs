pub fn all_ids() -> Vec<u8> {
    ROWS.iter().flat_map(|r| r.iter()).filter(|k| k.id != 0).map(|k| k.id).collect()
}

pub const WASD: [u8; 4] = [18, 31, 32, 33];
/// Firmware id of the Fn key. Never remapped.
pub const FN_KEY: u8 = 59;

pub fn label(id: u8) -> &'static str {
    ROWS.iter().flat_map(|r| r.iter()).find(|k| k.id == id).map(|k| k.label).unwrap_or("?")
}

