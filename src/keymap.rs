/// Name for a HID usage, using the key that produces it by default.
pub fn hid_name(hid: u8) -> String {
    for r in ROWS {
        for k in r.iter() {
            if k.id != 0 && default_hid(k.id) == Some(hid) {
                return k.label.to_string();
            }
        }
    }
    format!("0x{hid:02x}")
}
